import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import type { SfxCueId } from '../../src/audio/engine.ts';

const APPROVED_CATALOG_SHA256 = 'e8ef8aea8a0b3840da3ef23d9967fb23c964e6255c120f3753b03f81a56718f6';
const STAGING_PATH = 'assets-source/audio/sfx/staging';
const OUTPUT_PATH = 'src/audio/recorded-game-sfx.ts';
const FORMATS = ['ogg', 'mp3'] as const;

interface Derivative {
  readonly file: string;
  readonly bytes: number;
  readonly sha256: string;
}

interface Cue {
  readonly id: SfxCueId;
  readonly derivatives: Readonly<Record<(typeof FORMATS)[number], Derivative>>;
}

function sha256(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex');
}

async function approvedCues(staging: string): Promise<readonly Cue[]> {
  const catalog = await readFile(join(staging, 'catalog.json'));
  if (sha256(catalog) !== APPROVED_CATALOG_SHA256) {
    throw new Error('Game sound effects catalog differs from the owner-approved revision');
  }
  return (JSON.parse(catalog.toString('utf8')) as { cues: readonly Cue[] }).cues;
}

function assertApprovedBytes(cue: Cue, format: (typeof FORMATS)[number], bytes: Uint8Array): void {
  const approved = cue.derivatives[format];
  if (bytes.byteLength !== approved.bytes || sha256(bytes) !== approved.sha256) {
    throw new Error(`Game sound effects differ from the approved bytes for ${cue.id} (${format})`);
  }
}

export async function verifyRecordedGameSfx(root: string): Promise<number> {
  const cues = await approvedCues(join(root, STAGING_PATH));
  const { readRecordedGameCue } = await import('../../src/audio/recorded-game-sfx.ts');
  for (const cue of cues) {
    for (const format of FORMATS) {
      assertApprovedBytes(cue, format, new Uint8Array(readRecordedGameCue(cue.id, format)));
    }
  }
  return cues.length;
}

async function packSfx(root: string, staging: string): Promise<void> {
  const cues = await approvedCues(staging);
  const recordings: Buffer[] = [];
  let offset = 0;
  const ranges: string[] = [];
  for (const cue of cues) {
    const lengths: number[] = [];
    for (const format of FORMATS) {
      const bytes = await readFile(join(staging, cue.derivatives[format].file));
      assertApprovedBytes(cue, format, bytes);
      recordings.push(bytes);
      lengths.push(bytes.length);
    }
    const key = /^[a-z]+$/.test(cue.id) ? cue.id : `'${cue.id}'`;
    ranges.push(`  ${key}: [${offset}, ${lengths.join(', ')}],`);
    offset += cue.derivatives.ogg.bytes + cue.derivatives.mp3.bytes;
  }
  const bank =
    Buffer.concat(recordings)
      .toString('base64')
      .match(/.{1,120}/g)
      ?.join('\n') ?? '';
  await writeFile(
    join(root, OUTPUT_PATH),
    `// Generated by scripts/assets/pack-game-sfx.ts from the approved Rift Bastion recordings.
// The encoded audio in this module is governed by the ElevenLabs Sound Effects terms.
import type { SfxCueId } from './engine.ts';

const CUE_RANGES: Readonly<Record<SfxCueId, readonly [number, number, number]>> = {
${ranges.join('\n')}
};

const GAME_AUDIO = \`
${bank}
\`;

let decoded: Uint8Array<ArrayBuffer> | undefined;

/** Returns a fresh decoder input because Web Audio takes ownership of the buffer. */
export function readRecordedGameCue(cue: SfxCueId, format: 'ogg' | 'mp3'): ArrayBuffer {
  if (!decoded) {
    const raw = atob(GAME_AUDIO);
    const bytes = new Uint8Array(raw.length);
    for (let i = 0; i < raw.length; i += 1) bytes[i] = raw.charCodeAt(i);
    decoded = bytes;
  }
  const [offset, oggBytes, mp3Bytes] = CUE_RANGES[cue];
  return format === 'ogg'
    ? decoded.slice(offset, offset + oggBytes).buffer
    : decoded.slice(offset + oggBytes, offset + oggBytes + mp3Bytes).buffer;
}
`,
    'utf8',
  );
}

if (import.meta.main) {
  const root = resolve(import.meta.dirname, '../..');
  const [flag, directory] = Bun.argv.slice(2);
  if (flag === '--pack') await packSfx(root, directory ?? join(root, STAGING_PATH));
  else if (flag !== undefined && flag !== '--verify') {
    throw new Error('Use --pack [staging-directory] or --verify');
  }
  const count = await verifyRecordedGameSfx(root);
  console.log(`Verified ${count} approved game sound effects in both codecs.`);
}
